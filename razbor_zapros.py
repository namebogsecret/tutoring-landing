LEAD = ("Выберите запрос, который ближе всего к вашему: ниже готовый план на четыре недели. "
        "На разборе мы подстроим его под ваш уровень, дату экзамена и число занятий в неделю.")


def _card(r):
    weeks = "".join(
        f'<li><strong>Неделя {i}. {t}.</strong><ul>' + "".join(f"<li>{x}</li>" for x in items) + "</ul></li>"
        for i, (t, items) in enumerate(r["weeks"], 1))
    block = razbor_block_html(r["slug"], "ru", with_script=False,
                              title="Разбор по этому запросу",
                              lead="Принесите пробную работу или задачи, на которых застряли: разберём их и подстроим план под вас.")
    return (f'<article class="razbor-card" id="{r["slug"]}" data-razbor-slug="{r["slug"]}">\n'
            f'  <h3>{r["name"]}</h3>\n  <p class="razbor-q">{r["query"]}</p>\n'
            f'  <details class="razbor-plan"><summary>План на 4 недели</summary>\n    <ol>{weeks}</ol>\n  </details>\n'
            f'  {block}\n</article>')


